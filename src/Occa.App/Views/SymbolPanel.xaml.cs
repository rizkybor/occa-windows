using Microsoft.UI.Xaml;
using Microsoft.UI.Xaml.Controls;
using Microsoft.UI.Xaml.Media;
using Occa.Core.Sheet;
using Occa.Core.Vector;

namespace Occa.App.Views;

/// <summary>One row of the symbol list (public for x:Bind).</summary>
public sealed class SymbolRow
{
    public required MapSymbol Symbol { get; init; }
    public string Code => Symbol.Code;
    public string Name => Symbol.Name;
    public string Glyph => Symbol.SymbolKind switch { MapSymbol.Kind.Point => "", MapSymbol.Kind.Line => "", MapSymbol.Kind.Area => "", _ => "" };
    public Brush Swatch => new SolidColorBrush(Occa.Render.MapRenderer.ToColor(Symbol.ColorHex));
    public Brush Ink
    {
        get
        {
            var rgb = ColorHex.Rgb(Symbol.ColorHex) ?? (0, 0, 0);
            double luma = 0.299 * rgb.R + 0.587 * rgb.G + 0.114 * rgb.B;
            return new SolidColorBrush(luma > 0.6 ? Windows.UI.Color.FromArgb(255, 0x2B, 0x2A, 0x28) : Windows.UI.Color.FromArgb(255, 255, 255, 255));
        }
    }
}

/// <summary>
/// Symbols panel (FR-W2): the sheet standard's built-in set (ISOM / ISSprOM / ISInOM, generated by CakraCore) with
/// search and category filter. Choosing a symbol makes it the active drawing symbol and tells the map view which tool
/// fits; "Apply to selection" changes the selected object's symbol (<c>FeatureEdit.SwitchSymbol</c>).
/// </summary>
public sealed partial class SymbolPanel : UserControl
{
    /// <summary>The active symbol changed (also null when cleared).</summary>
    public event EventHandler? SymbolChosen;
    public event EventHandler? ApplyRequested;
    public event EventHandler? CloseRequested;

    private List<MapSymbol> _all = new();
    private bool _updating;

    public MapSymbol? ActiveSymbol { get; private set; }
    /// <summary>Size multiplier for new objects (1 = IOF standard).</summary>
    public double SizeFactor => double.IsNaN(SizeBox.Value) ? 1 : Math.Clamp(SizeBox.Value / 100, 0.5, 3);

    public SymbolPanel()
    {
        InitializeComponent();
    }

    public void Bind(SheetSpec sheet)
    {
        var file = StandardSymbolSets.For(sheet.MapStandard);
        _all = file.Symbols.Where(s => s.IsEnabled && s.IsDrawable).OrderBy(s => s.Number).ToList();
        SetText.Text = $"{file.Name} · {_all.Count} symbols";
        _updating = true;
        CategoryBox.Items.Clear();
        CategoryBox.Items.Add(new ComboBoxItem { Content = "All categories", Tag = null });
        foreach (var cat in _all.Select(s => s.Category).Distinct().OrderBy(c => (int)c))
            CategoryBox.Items.Add(new ComboBoxItem { Content = CategoryLabel(cat), Tag = cat });
        CategoryBox.SelectedIndex = 0;
        _updating = false;
        ActiveSymbol = null;
        ActiveText.Text = "Choose a symbol, then draw with the Pen, Freehand, Rectangle, Ellipse or Point tool.";
        Refresh();
    }

    private static string CategoryLabel(SymbolCategory c) => c switch
    {
        SymbolCategory.Landform => "Land forms (1xx)",
        SymbolCategory.Rock => "Rock and boulders (2xx)",
        SymbolCategory.Water => "Water and marsh (3xx)",
        SymbolCategory.Vegetation => "Vegetation (4xx)",
        SymbolCategory.ManMade => "Man-made features (5xx)",
        SymbolCategory.Technical => "Technical symbols (6xx)",
        SymbolCategory.Course => "Course setting (7xx)",
        SymbolCategory.IndoorConstruction => "Indoor: construction",
        SymbolCategory.IndoorFloor => "Indoor: floors",
        SymbolCategory.IndoorWater => "Indoor: water",
        SymbolCategory.IndoorFurniture => "Indoor: furniture",
        SymbolCategory.IndoorDirections => "Indoor: directions",
        _ => "Other",
    };

    /// <summary>Enables "Apply to selection" when an object is selected on the map.</summary>
    public void SetSelection(bool hasSelection) => ApplyButton.IsEnabled = hasSelection && ActiveSymbol is not null;

    private void Refresh()
    {
        _updating = true;
        var query = SearchBox.Text?.Trim() ?? "";
        var category = CategoryBox.SelectedItem is ComboBoxItem { Tag: SymbolCategory c } ? c : (SymbolCategory?)null;
        var rows = _all.Where(s => category is null || s.Category == category)
            .Where(s => query.Length == 0 || s.Code.StartsWith(query, StringComparison.OrdinalIgnoreCase) || s.Name.Contains(query, StringComparison.OrdinalIgnoreCase))
            .Select(s => new SymbolRow { Symbol = s }).ToList();
        SymbolList.ItemsSource = rows;
        SymbolList.SelectedIndex = ActiveSymbol is null ? -1 : rows.FindIndex(r => r.Symbol.Number == ActiveSymbol.Number);
        _updating = false;
    }

    private void SearchBox_TextChanged(AutoSuggestBox sender, AutoSuggestBoxTextChangedEventArgs args) => Refresh();
    private void CategoryBox_SelectionChanged(object sender, SelectionChangedEventArgs e) { if (!_updating) Refresh(); }

    private void SymbolList_SelectionChanged(object sender, SelectionChangedEventArgs e)
    {
        if (_updating || SymbolList.SelectedItem is not SymbolRow row) return;
        ActiveSymbol = row.Symbol;
        var kind = row.Symbol.SymbolKind switch { MapSymbol.Kind.Point => "point symbol · Point tool (T)", MapSymbol.Kind.Line => "line · Pen (P) or Freehand (F)", MapSymbol.Kind.Area => "area · Pen (P), Rectangle (M) or Ellipse (L)", _ => "text" };
        ActiveText.Text = $"{row.Symbol.Code} {row.Symbol.Name} · {kind}";
        SymbolChosen?.Invoke(this, EventArgs.Empty);
    }

    private void SizeBox_ValueChanged(NumberBox sender, NumberBoxValueChangedEventArgs args) => SymbolChosen?.Invoke(this, EventArgs.Empty);
    private void Apply_Click(object sender, RoutedEventArgs e) => ApplyRequested?.Invoke(this, EventArgs.Empty);
    private void Close_Click(object sender, RoutedEventArgs e) => CloseRequested?.Invoke(this, EventArgs.Empty);
}
